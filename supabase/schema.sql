-- Politiques pour PRODUCTS :
-- Tout le monde peut consulter les produits
CREATE POLICY "Lecture publique des produits"
  ON public.products FOR SELECT
  USING (true);

-- Ajout, modification et suppression de produits
CREATE POLICY "Gestion des produits"
  ON public.products FOR ALL
  USING (true)
  WITH CHECK (true);

-- Politiques pour ORDERS :
-- Les clients (connectés ou invités) peuvent passer commande
CREATE POLICY "Création de commande"
  ON public.orders FOR INSERT
  WITH CHECK (true);

-- Lecture des commandes
CREATE POLICY "Lecture des commandes"
  ON public.orders FOR SELECT
  USING (true);

-- Mise à jour des commandes (pour changer le statut de livraison)
CREATE POLICY "Mise à jour des commandes"
  ON public.orders FOR UPDATE
  USING (true);

-- Politiques pour PROFILES :
CREATE POLICY "Lecture des profils"
  ON public.profiles FOR SELECT
  USING (true);

CREATE POLICY "Gestion des profils"
  ON public.profiles FOR ALL
  USING (true)
  WITH CHECK (true);

-- ==============================================================================
-- TRIGGER AUTOMATIQUE POUR UPDATED_AT SUR PRODUCTS
-- ==============================================================================
CREATE OR REPLACE FUNCTION update_updated_at_column()
RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at = timezone('utc'::text, now());
  RETURN NEW;
END;
$$ language 'plpgsql';

DROP TRIGGER IF EXISTS trigger_update_products_updated_at ON public.products;
CREATE TRIGGER trigger_update_products_updated_at
  BEFORE UPDATE ON public.products
  FOR EACH ROW
  EXECUTE FUNCTION update_updated_at_column();

