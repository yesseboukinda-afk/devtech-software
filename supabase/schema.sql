-- 1. Table des produits (Products)
CREATE TABLE IF NOT EXISTS public.products (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title TEXT NOT NULL,
  brand TEXT,
  category TEXT NOT NULL,
  image TEXT,
  images JSONB DEFAULT '[]'::jsonb,
  price NUMERIC NOT NULL,
  old_price NUMERIC,
  rating NUMERIC DEFAULT 5.0,
  reviews_count INTEGER DEFAULT 0,
  bought_past_month TEXT,
  prime BOOLEAN DEFAULT false,
  amazon_choice BOOLEAN DEFAULT false,
  best_seller BOOLEAN DEFAULT false,
  deal BOOLEAN DEFAULT false,
  deal_discount INTEGER DEFAULT 0,
  stock INTEGER DEFAULT 0,
  features JSONB DEFAULT '[]'::jsonb,
  sku TEXT,
  warranty TEXT,
  delivery_date TEXT,
  created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
  updated_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- Index pour accélérer les recherches et filtres
CREATE INDEX IF NOT EXISTS idx_products_category ON public.products(category);
CREATE INDEX IF NOT EXISTS idx_products_created_at ON public.products(created_at DESC);

-- 2. Table des commandes (Orders)
CREATE TABLE IF NOT EXISTS public.orders (
  id TEXT PRIMARY KEY,
  customer_name TEXT NOT NULL,
  customer_phone TEXT NOT NULL,
  customer_email TEXT,
  delivery_address TEXT NOT NULL,
  payment_method TEXT NOT NULL,
  items JSONB NOT NULL DEFAULT '[]'::jsonb,
  subtotal NUMERIC NOT NULL,
  shipping_fee NUMERIC DEFAULT 0,
  total NUMERIC NOT NULL,
  status TEXT DEFAULT 'En attente de traitement',
  user_id UUID REFERENCES auth.users(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_orders_created_at ON public.orders(created_at DESC);

-- 3. Table des profils utilisateurs (Profiles)
CREATE TABLE IF NOT EXISTS public.profiles (
  id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  email TEXT,
  name TEXT,
  role TEXT DEFAULT 'client',
  phone TEXT,
  country TEXT DEFAULT 'Gabon',
  province TEXT,
  city TEXT,
  district TEXT,
  id_number TEXT,
  avatar TEXT,
  photo_url TEXT,
  created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- ==============================================================================
-- SÉCURITÉ ROW LEVEL SECURITY (RLS)
